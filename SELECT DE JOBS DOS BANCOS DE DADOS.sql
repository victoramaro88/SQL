SELECT
	S.job_id AS JobId
	,S.name AS NomeJob 
	,CONCAT(LEFT(H.run_date,4),'-',SUBSTRING(CONVERT(VARCHAR(8),H.run_date),5,2), '-',RIGHT(H.run_date,2)) AS Dia
	,CONVERT(DATETIME, RTRIM(H.run_date)) +  (H.run_time * 9 + H.run_time % 10000 * 6 + H.run_time % 100 * 10) / 216e4 AS DataHora
	,H.run_status AS IDStatus
	,CASE
		WHEN H.run_status = 0 THEN 'FALHOU'
		WHEN H.run_status = 1 THEN 'SUCEDIDO'
		WHEN H.run_status = 2 THEN 'REPETIR'
		WHEN H.run_status = 3 THEN 'CANCELADO'
		WHEN H.run_status = 4 THEN 'EM ANDAMENTO'
	END AS Status
FROM msdb..sysjobs S
LEFT JOIN msdb..sysjobhistory H ON S.job_id = H.job_id AND H.step_name NOT IN ('Run agent.','Log shipping backup log job step.','(Job outcome)')
INNER JOIN 
	(
		SELECT 
		job_id,  
		run_status, 
		run_date, 
		run_time, 
		CONVERT(DATETIME, RTRIM(run_date)) +  (run_time * 9 + run_time % 10000 * 6 + run_time % 100 * 10) / 216e4 DATA_HORA,
		ROW_NUMBER() OVER (PARTITION BY job_id ORDER BY CONVERT(DATETIME, RTRIM(run_date)) +  (run_time * 9 + run_time % 10000 * 6 + run_time % 100 * 10) / 216e4 DESC) RownNum
	FROM msdb..sysjobhistory 
	WHERE step_name NOT IN ('Run agent.','Log shipping backup log job step.','(Job outcome)') 
	AND CONCAT(LEFT(run_date,4),'-',SUBSTRING(CONVERT(VARCHAR(8),run_date),5,2), '-',RIGHT(run_date,2)) BETWEEN CAST(GETDATE()-30 AS DATE) AND CAST(GETDATE() AS DATE)
	) H2 ON H2.RownNum <= 2 AND H.job_id = H2.job_id AND H.run_date = H2.run_date AND  H.run_time = H2.run_time AND H.run_status = H2.run_status
WHERE S.enabled = 1
AND H2.RownNum <= 2
GROUP BY 
	S.job_id 
	,S.name
	,H.run_date
	,H.run_time
	,H.run_status
