	DB_CARGA_SIOPM.SchNOC.PTR PTR
	ON RTRIM(LTRIM(PTRDSL.PtrIdf)) = RTRIM(LTRIM(PTR.PtrIdf))LEFT JOIN
	DB_CARGA_SIOPM.dbo.NAT NAT
