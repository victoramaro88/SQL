	ALE.AleLat AS LAT,
	RTRIM(LTRIM(PTRDSL.PtrIdf)) US_PFX,
	CONCAT(UPPER (CAST ((
		SELECT RTRIM(HISOCOR.HisOcrDes) + ';'
                        FROM DB_CARGA_SIOPM.SchNOC.HISOCR AS HISOCOR
                        WHERE HISOCOR.OcrNum = OCR.OcrNum
                                AND HISOCOR.OcrDat = OCR.OcrDat AND HISOCOR.CadCod = OCR.CadCod
